/**
 * Generate width variants for the raster images in public/images.
 *
 * Every cover is shipped at its full intrinsic size - up to 3014px wide - and
 * then rendered into a card a few hundred pixels across. Lighthouse put 374KB
 * on mobile and 503KB on desktop against that, and it also counts toward
 * GTmetrix's Structure score, which is 40% of their grade.
 *
 * Astro's <Image> cannot help here: it only optimises images imported from
 * src/, and these are referenced as string paths out of public/ by the data
 * layer. Rather than move 17 files and rewrite every reference, this emits
 * <name>-<width>.<ext> next to each original and srcsetFor() in src/lib/img.ts
 * builds the srcset from the same list.
 *
 * Idempotent: a variant that already exists and is newer than its source is
 * left alone, so repeat builds cost nothing. Variants are gitignored and
 * regenerated by the prebuild step.
 */
import { readdir, stat, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

export const WIDTHS = [480, 768, 1200];
const ROOT = path.join(process.cwd(), "public", "images");
const EXT = new Set([".webp", ".avif", ".jpg", ".jpeg", ".png"]);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

/** `/images/a/b.webp` + 480 -> `/images/a/b-480.webp` */
export function variantPath(file, width) {
  const ext = path.extname(file);
  return `${file.slice(0, -ext.length)}-${width}${ext}`;
}

let made = 0, skipped = 0;
for await (const file of walk(ROOT)) {
  const ext = path.extname(file).toLowerCase();
  if (!EXT.has(ext)) continue;
  // Never treat an already-generated variant as a source.
  if (/-\d+$/.test(path.basename(file, ext))) continue;

  const meta = await sharp(file).metadata();
  const source = await stat(file);

  for (const width of WIDTHS) {
    // Upscaling would be larger than the original and no sharper.
    if (!meta.width || meta.width <= width) continue;
    const out = variantPath(file, width);
    if (existsSync(out) && (await stat(out)).mtimeMs >= source.mtimeMs) { skipped++; continue; }
    await mkdir(path.dirname(out), { recursive: true });
    const pipeline = sharp(file).resize({ width, withoutEnlargement: true });
    await (ext === ".avif"
      ? pipeline.avif({ quality: 55 })
      : ext === ".png"
        ? pipeline.png({ compressionLevel: 9 })
        : ext === ".webp"
          ? pipeline.webp({ quality: 78 })
          : pipeline.jpeg({ quality: 78, mozjpeg: true })
    ).toFile(out);
    made++;
  }
}
console.log(`[responsive-images] ${made} generated, ${skipped} already current`);
